"""Byte-for-byte comparison of vouch_hub.normalise against the real Dart
TranscriptMatcher, via tests/transcript_vectors.json (generated by
vouch/vouch_server/tool/gen_transcript_vectors.dart).
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from vouch_hub.normalise import normalise, transcript_hash

VECTORS_PATH = Path(__file__).parent / "transcript_vectors.json"


def _load_vectors():
    if not VECTORS_PATH.exists():
        return []
    return json.loads(VECTORS_PATH.read_text())


VECTORS = _load_vectors()


def test_vectors_present():
    assert VECTORS, (
        "tests/transcript_vectors.json is missing or empty. Regenerate with:\n"
        "  cd vouch/vouch_server && dart run tool/gen_transcript_vectors.dart "
        "> ../../hub/tests/transcript_vectors.json"
    )


import pytest


@pytest.mark.parametrize("vector", VECTORS, ids=lambda v: v["input"])
def test_normalise_matches_dart(vector):
    result = normalise(vector["input"])
    assert result == vector["normalised"], (
        f"normalise({vector['input']!r}) = {result!r}, "
        f"Dart produced {vector['normalised']!r}"
    )


@pytest.mark.parametrize("vector", VECTORS, ids=lambda v: v["input"])
def test_hash_matches_dart(vector):
    result = transcript_hash(vector["normalised"])
    assert result == vector["hash"]
